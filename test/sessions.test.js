'use strict';

const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const {
  discoverSessions,
  findActiveSession,
  findSessionById,
  readLastUsage,
  readSessionMeta
} = require('../src/sessions');

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'zero-sessions-'));

function writeSession(slug, id, { cwd, title, mtime, lines }) {
  const dir = path.join(tmp, '.zero', 'projects', slug);
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, `${id}.jsonl`);
  const content = lines || [
    JSON.stringify({ type: '_spec', started_at: '2026-01-01T00:00:00Z' }),
    JSON.stringify({
      type: 'user',
      message: { role: 'user', content: title },
      cwd,
      timestamp: '2026-01-01T00:00:01Z'
    }),
    JSON.stringify({
      type: 'assistant',
      message: { content: [{ type: 'text', text: 'ok' }] },
      cwd
    })
  ];
  fs.writeFileSync(file, content.join('\n') + '\n');
  const seconds = mtime / 1000;
  fs.utimesSync(file, seconds, seconds);
  return file;
}

try {
  const now = Date.now();
  writeSession('-home-alice', '11111111-1111-4111-8111-111111111111', {
    cwd: '/home/alice',
    title: 'old terminal session',
    mtime: now - 60_000
  });
  writeSession('-home-alice-project', '22222222-2222-4222-8222-222222222222', {
    cwd: '/home/alice/project',
    title: 'newer project session',
    mtime: now - 10_000
  });

  const caveat = writeSession('-home-bob', '33333333-3333-4333-8333-333333333333', {
    cwd: '/home/bob',
    mtime: now - 30_000,
    lines: [
      JSON.stringify({ type: '_spec', started_at: '2026-01-01T00:00:00Z' }),
      JSON.stringify({
        type: 'user',
        message: {
          role: 'user',
          content: '<local-command-caveat>generated by a local command</local-command-caveat>'
        },
        cwd: '/home/bob'
      }),
      JSON.stringify({
        type: 'user',
        message: { role: 'user', content: 'real question from bob' },
        cwd: '/home/bob'
      })
    ]
  });

  const meta = readSessionMeta(caveat);
  assert.strictEqual(meta.cwd, '/home/bob', 'cwd is read');
  assert.strictEqual(meta.title, 'real question from bob', 'caveat title is skipped');

  const list = discoverSessions(tmp, 10);
  assert.strictEqual(list.length, 3, 'finds sessions in every project');
  assert.deepStrictEqual(
    list.map(session => session.id.slice(0, 1)),
    ['2', '3', '1'],
    'sorted by mtime descending'
  );
  assert.strictEqual(list[0].cwd, '/home/alice/project');
  assert.strictEqual(list[0].title, 'newer project session');
  assert.strictEqual(list[0].index, 1);
  assert.strictEqual(list[2].cwd, '/home/alice');

  const limited = discoverSessions(tmp, 1);
  assert.strictEqual(limited.length, 1, 'respects the limit');
  assert.strictEqual(limited[0].id, '22222222-2222-4222-8222-222222222222');

  const found = findSessionById(tmp, '11111111-1111-4111-8111-111111111111');
  assert.ok(found, 'finds an exact session ID');
  assert.strictEqual(found.cwd, '/home/alice');
  assert.strictEqual(found.title, 'old terminal session');
  assert.strictEqual(findSessionById(tmp, 'does-not-exist'), null);

  const usageFile = writeSession('-home-carol', '44444444-4444-4444-8444-444444444444', {
    cwd: '/home/carol',
    mtime: now - 20_000,
    lines: [
      JSON.stringify({ type: '_spec', started_at: '2026-01-01T00:00:00Z' }),
      JSON.stringify({
        type: 'user',
        message: { role: 'user', content: 'usage test' },
        cwd: '/home/carol'
      }),
      JSON.stringify({
        type: 'assistant',
        message: {
          usage: { input_tokens: 100, cache_read_input_tokens: 900, output_tokens: 50 }
        }
      }),
      JSON.stringify({
        type: 'assistant',
        message: {
          usage: { input_tokens: 200, cache_read_input_tokens: 1800, output_tokens: 75 }
        }
      })
    ]
  });
  assert.strictEqual(readLastUsage(usageFile), 2075, 'reads the last usage entry');

  const noUsage = writeSession('-home-dave', '55555555-5555-4555-8555-555555555555', {
    cwd: '/home/dave',
    mtime: now - 5_000
  });
  assert.strictEqual(readLastUsage(noUsage), null, 'returns null without usage');

  const registry = path.join(tmp, '.zero', 'sessions');
  fs.mkdirSync(registry, { recursive: true });
  fs.writeFileSync(
    path.join(registry, `${process.pid}.json`),
    JSON.stringify({
      pid: process.pid,
      sessionId: '11111111-1111-4111-8111-111111111111',
      cwd: '/home/alice',
      kind: 'interactive',
      entrypoint: 'cli'
    })
  );
  const active = findActiveSession(
    tmp,
    '11111111-1111-4111-8111-111111111111',
    { verifyProcess: false }
  );
  assert.ok(active, 'detects the exact active session');
  assert.strictEqual(active.pid, process.pid);
  assert.strictEqual(active.cwd, '/home/alice');
  assert.strictEqual(findActiveSession(
    tmp,
    '22222222-2222-4222-8222-222222222222',
    { verifyProcess: false }
  ), null);

  if (process.platform === 'linux') {
    // The test runner is Node, not an interactive Zero CLI.
    assert.strictEqual(
      findActiveSession(tmp, '11111111-1111-4111-8111-111111111111'),
      null,
      'rejects non-interactive processes'
    );
  }

  fs.writeFileSync(
    path.join(registry, '999999.json'),
    JSON.stringify({
      pid: 999999,
      sessionId: 'dead-session',
      cwd: '/home/dead',
      kind: 'interactive'
    })
  );
  assert.strictEqual(findActiveSession(tmp, 'dead-session'), null, 'ignores dead PIDs');

  fs.writeFileSync(
    path.join(registry, 'print.json'),
    JSON.stringify({
      pid: process.pid,
      sessionId: 'print-session',
      cwd: '/home/print',
      kind: 'print'
    })
  );
  assert.strictEqual(findActiveSession(tmp, 'print-session'), null, 'ignores non-interactive entries');

  console.log('sessions tests passed');
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}
